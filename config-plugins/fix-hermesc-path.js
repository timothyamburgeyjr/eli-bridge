// Expo config plugin: point `hermesCommand` at the REAL hermesc.
//
// RN 0.82's Android template writes this into android/app/build.gradle:
//
//   hermesCommand = <resolve 'hermes-compiler'> + "/hermesc/%OS-BIN%/hermesc"
//
// In this install, `hermes-compiler` is a 0.0.0 stub package containing only a
// package.json — there are no binaries under it. The actual hermesc binaries
// ship inside react-native itself, at:
//
//   node_modules/react-native/sdks/hermesc/<os-bin>/hermesc[.exe]
//
// Consequence: DEBUG builds are fine (they never compile Hermes bytecode — the
// JS is served from Metro), but every RELEASE build dies in
// :app:createBundleReleaseJsAndAssets with a bare, unhelpful
//
//   The system cannot find the path specified.
//
// right after "Done writing bundle output" — which reads like a bundler problem
// and isn't one.
//
// config-plugins/disable-hermes-v1.js sets hermesV1Enabled=false for the same
// underlying reason, but that gradle property does NOT help here: the explicit
// `hermesCommand` assignment in build.gradle overrides it. Both fixes are
// needed, and this one has to live in a plugin because android/ is gitignored
// and regenerated by `expo prebuild`.

const { withAppBuildGradle } = require("@expo/config-plugins");

const STUB = /hermesCommand\s*=\s*new File\(\["node",\s*"--print",\s*"require\.resolve\('hermes-compiler\/package\.json'[^\n]*\n/;

const REAL =
  '    hermesCommand = new File(["node", "--print", "require.resolve(\'react-native/package.json\')"]' +
  '.execute(null, rootDir).text.trim()).getParentFile().getAbsolutePath() + "/sdks/hermesc/%OS-BIN%/hermesc"\n';

/** @param {import("@expo/config").ExpoConfig} config */
module.exports = function withFixHermescPath(config) {
  return withAppBuildGradle(config, (c) => {
    const src = c.modResults.contents;

    if (src.includes("/sdks/hermesc/%OS-BIN%/hermesc")) {
      return c; // already correct
    }
    if (!STUB.test(src)) {
      // The template changed shape. Fail loudly rather than silently shipping a
      // config that only breaks on release builds, which is how this hid for
      // months in the first place.
      throw new Error(
        "[fix-hermesc-path] Could not find the hermesCommand assignment in " +
          "android/app/build.gradle. RN's template likely changed — re-check " +
          "whether hermesc still resolves to the `hermes-compiler` stub."
      );
    }

    c.modResults.contents = src.replace(STUB, REAL);
    return c;
  });
};
